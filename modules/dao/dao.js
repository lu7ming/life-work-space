  // ===== 农历转换（简化版，覆盖2025-2028，复用dashboard逻辑） =====
  function solarToLunar(date) {
    const d = new Date(date.getFullYear(), date.getMonth(), date.getDate());

    // 2025年
    const sf2025 = new Date(2025, 0, 29);
    const months2025 = [29,30,29,30,29,30,29,30,29,30,30,29];
    const leap2025 = 0;

    // 2026年：春节2月17日，闰六月
    const sf2026 = new Date(2026, 1, 17);
    const months2026 = [29,29,30,29,30,29, 29,30,29,30,29,30,29];
    const leap2026 = 6;

    // 2027年：春节2月6日，无闰月
    const sf2027 = new Date(2027, 1, 6);
    const months2027 = [30,29,30,29,30,29,30,29,30,29,30,29];
    const leap2027 = 0;

    // 2028年：春节1月26日，闰五月
    const sf2028 = new Date(2028, 0, 26);
    const months2028 = [29,30,29,30,29, 30,29,30,29,30,29,30,29];
    const leap2028 = 5;

    let springDate, months, leapMonth, lunarYear;
    if (d >= sf2028) {
      springDate = sf2028; months = months2028; leapMonth = leap2028; lunarYear = 2028;
    } else if (d >= sf2027) {
      springDate = sf2027; months = months2027; leapMonth = leap2027; lunarYear = 2027;
    } else if (d >= sf2026) {
      springDate = sf2026; months = months2026; leapMonth = leap2026; lunarYear = 2026;
    } else {
      springDate = sf2025; months = months2025; leapMonth = leap2025; lunarYear = 2025;
    }

    const diff = Math.floor((d - springDate) / 86400000);
    if (diff < 0) return null;

    let lunarMonth = 0, lunarDay = 0, isLeap = false;
    let remaining = diff;

    for (let i = 0; i < months.length; i++) {
      if (remaining < months[i]) {
        if (leapMonth > 0 && i === leapMonth) {
          isLeap = true;
          lunarMonth = i;
        } else if (leapMonth > 0 && i > leapMonth) {
          lunarMonth = i;
        } else {
          lunarMonth = i + 1;
        }
        lunarDay = remaining + 1;
        break;
      }
      remaining -= months[i];
    }

    if (lunarMonth === 0) lunarMonth = 1;

    return { year: lunarYear, month: lunarMonth, day: lunarDay, isLeap };
  }

  // 年支数：子1丑2...亥12
  function getYearZhi(lunarYear) {
    // (lunarYear - 4) % 12 => 0=子,1=丑...
    return ((lunarYear - 4) % 12 + 12) % 12 + 1;
  }

  // 时支数：子时23-1点=1，丑时1-3点=2...亥时21-23点=12
  function getHourZhi(hour) {
    // 子时: 23-1 => (hour + 1) // 2 => (23+1)/2=12, (0+1)/2=0.5→取整为0
    // 调整：(hour + 1) % 24 // 2 + 1 ... 不对
    // 0-1点=子时(1), 2-3=丑(2), 4-5=寅(3), 6-7=卯(4), 8-9=辰(5), 10-11=巳(6)
    // 12-13=午(7), 14-15=未(8), 16-17=申(9), 18-19=酉(10), 20-21=戌(11), 22-23=亥(12)
    // 注意：23点属次日子时
    let h = hour;
    if (h === 23) return 1;
    return Math.floor((h + 1) / 2) + 1;
  }

  // ===== 梅花易数：年月日时起卦 =====
  function meihuaQiGua(date) {
    const lunar = solarToLunar(date);
    if (!lunar) return null;

    const yearZhi = getYearZhi(lunar.year);
    const hourZhi = getHourZhi(date.getHours());

    const upperSum = yearZhi + lunar.month + lunar.day;
    const lowerSum = yearZhi + lunar.month + lunar.day + hourZhi;

    let upperNum = upperSum % 8;
    if (upperNum === 0) upperNum = 8;

    let lowerNum = lowerSum % 8;
    if (lowerNum === 0) lowerNum = 8;

    let dongYao = lowerSum % 6;
    if (dongYao === 0) dongYao = 6;

    // 找本卦
    const benGua = GUADATA.find(g => g.upper === upperNum && g.lower === lowerNum);

    // 计算互卦：2、3、4爻为下互，3、4、5爻为上互（注意yaos数组从上到下）
    // yaos索引：0=上爻 1=五爻 2=四爻 3=三爻 4=二爻 5=初爻
    // 上互卦（三爻四爻五爻）：索引1,2,3 → [五,四,三] 从上到下
    // 下互卦（二爻三爻四爻）：索引2,3,4 → [四,三,二] 从上到下
    const benYaos = benGua.yaos;
    const shangHuYaos = [benYaos[1], benYaos[2], benYaos[3]]; // 五爻四爻三爻
    const xiaHuYaos = [benYaos[2], benYaos[3], benYaos[4]]; // 四爻三爻二爻

    // 找互卦对应的卦名
    const huGua = GUADATA.find(g => {
      const upperYaos = g.yaos.slice(0, 3);
      const lowerYaos = g.yaos.slice(3, 6);
      return arraysEqual(upperYaos, shangHuYaos) && arraysEqual(lowerYaos, xiaHuYaos);
    });

    // 计算变卦：动爻所在位阴阳互变
    // 动爻编号1-6对应初爻到上爻（从下往上）
    // yaos数组0=上爻(6), 5=初爻(1)
    const bianYaos = [...benYaos];
    const dongYaoIndex = 6 - dongYao; // 动爻1→索引5，动爻6→索引0
    bianYaos[dongYaoIndex] = bianYaos[dongYaoIndex] === 1 ? 0 : 1;

    const bianGua = GUADATA.find(g => arraysEqual(g.yaos, bianYaos));

    // 体用判断：动爻在下卦(1-3)则下卦为用，上卦为体；动爻在上卦(4-6)则上卦为用，下卦为体
    const tiGuaNum = dongYao <= 3 ? upperNum : lowerNum;
    const yongGuaNum = dongYao <= 3 ? lowerNum : upperNum;

    const tiGua = BAGUA_XIANTIAN[tiGuaNum];
    const yongGua = BAGUA_XIANTIAN[yongGuaNum];

    // 五行生克判断
    const shengke = analyzeShengke(tiGua.element, yongGua.element);

    return {
      benGua, huGua, bianGua,
      dongYao,
      tiGua, yongGua,
      shengke,
      lunar,
      yearZhi, hourZhi,
    };
  }

  function arraysEqual(a, b) {
    return a.length === b.length && a.every((v, i) => v === b[i]);
  }

  function analyzeShengke(tiElement, yongElement) {
    const relation = WUXING_SHENGKE[tiElement];
    // 用生体 -> 用的五行生体的五行
    if (WUXING_SHENGKE[yongElement].sheng === tiElement) {
      return { type: '用生体', level: '大吉', desc: '用卦生体卦，有外力相助，事情易得成功，吉祥顺遂。' };
    }
    // 体生用 -> 体的五行生用的五行
    if (relation.sheng === yongElement) {
      return { type: '体生用', level: '损耗', desc: '体卦生用卦，自身消耗大，付出多而回报少，劳心费力。' };
    }
    // 体克用 -> 体的五行克用的五行
    if (relation.ke === yongElement) {
      return { type: '体克用', level: '吉', desc: '体卦克用卦，自己能掌控局面，主动进取可成。' };
    }
    // 用克体 -> 用的五行克体的五行
    if (WUXING_SHENGKE[yongElement].ke === tiElement) {
      return { type: '用克体', level: '凶', desc: '用卦克体卦，有阻碍损害，诸事不利，宜谨慎守旧。' };
    }
    // 比和
    return { type: '体用比和', level: '顺', desc: '体用五行相同，比和相助，合作融洽，进展顺利。' };
  }

  // ===== 渲染卦象爻线（从上到下，CSS绘制） =====
  function renderYaoLines(yaos, dongYaoNum = 0) {
    // yaos: 数组从上到下（0=上爻，5=初爻）
    // dongYaoNum: 1-6，从下往上数的动爻编号
    let html = '';
    const labels = ['上爻', '五爻', '四爻', '三爻', '二爻', '初爻'];
    for (let i = 0; i < 6; i++) {
      const isYang = yaos[i] === 1;
      const yaoNum = 6 - i; // 从上到下：上爻=6，初爻=1
      const isDong = yaoNum === dongYaoNum;
      const yaoClass = isYang ? 'dao-yao-solid' : 'dao-yao-broken';
      const dongClass = isDong ? 'dao-yao-dong' : '';
      const dongMark = isDong ? '（动）' : '';
      html += `
        <div class="dao-yao-line ${yaoClass} ${dongClass}">
          <div class="dao-yao-bar yao-left"></div>
          <div class="yao-gap"></div>
          <div class="dao-yao-bar yao-right"></div>
          <div class="dao-yao-label">${labels[i]}${dongMark}</div>
        </div>`;
    }
    return html;
  }

